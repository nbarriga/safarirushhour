// ===== INSTRUMENTATION: metrics tracked during A* and along the solution path =====
struct SearchMetrics {
	double solver_time = 0.0;           // seconds
	int movements = 0;                  // solution length (moves)
	long expanded = 0;                  // number of node expansions
	long real_total = 0;                // successors generated by expanded nodes
	long eff_total = 0;                 // successors inserted or updated in open
	long repeated = 0;                  // successors discarded (already in open/closed with g <= new g)
	long reopened = 0;                  // closed nodes re-opened
	long open_list = 0, closed_list = 0;// final sizes
	int real_min = -1, real_max = -1, eff_min = -1, eff_max = -1;
	long sol_real_total = 0, sol_eff_total = 0, sol_repeated = 0;
	int sol_real_min = -1, sol_real_max = -1, sol_eff_min = -1, sol_eff_max = -1;
	// structural features of the initial board (7x7 grid, exit on the right edge of rows 3-4)
	int F1_pieces = 0, F2_cars = 0, F3_trucks = 0, F4_squares = 0;
	double F5_occupancy = 0.0;
	int F6_rover_exit_distance = 0, F7_rover_misalignment = 0, F8_direct_blockers = 0, F9_blocked_blockers = 0;
	double F10_horizontal_ratio = -1.0; // -1 = undefined (no rectangular pieces)
	bool solved = false;
};
